#!/usr/bin/env python
"""docs_tool.py - section long Markdown documents of the /analyze-then-pick library, keep them indexed, check the library.

A long document (a reference, a model guide) is stored as an INDEX file plus one file per section:

    reference/generation-system.md          the index: the original preamble + a generated table of sections
    reference/generation-system/010_1_the-dependency-chain.md
    reference/generation-system/020_2_work-backward.md ...

Section numbers (§4b.1c, §2.14) are unchanged, so every citation in the pipeline still resolves: look the number up in
the index table, or Glob  <doc>/*_<id>_*.md . Nothing here decides anything; it only cuts, joins, lists and checks.

  split  <doc.md> [--limit 8000]   cut a whole document into section files and turn <doc.md> into its index
  join   <doc.md> [--out FILE]     print (or write) the whole document again, byte for byte as it was
  index  <doc.md>                  rebuild the table of <doc.md> from the files in its folder (after an edit/add/rename)
  check  [--root ATP] [--skills DIR]   integrity of indexes, section files, skills, paths and citations (exit 1 on errors)
  budget [--root ATP] [--skills DIR]   size of every skill and of the files it names (what a phase loads)
  coverage [--root ATP] [--skills DIR] [--skill NAME]   every § citation a skill makes that its own "Read now" does not load

Part file name:  <seq>_<id>_<slug>.md   (seq = 010, 020, ... so a section can be inserted as 015_...)
"""
import argparse
import re
import sys
from pathlib import Path

HOME = Path.home() / ".claude"
ATP = HOME / "analyze-then-pick"
SKILLS = HOME / "skills"
MARK_A = "<!-- sections:start (generated by scripts/docs_tool.py index; do not edit between the markers) -->"
MARK_B = "<!-- sections:end -->"
HEAD = re.compile(r"^(#{2,4})[ \t]+(.*?)[ \t\r]*$")
NUM = re.compile(r"^(\d+[a-z]?(?:\.\d+[a-z]?)*)\.?(?:[ \t]+(.*))?$")


def rd(p):
    return Path(p).read_bytes().decode("utf-8")


def wr(p, text):
    Path(p).parent.mkdir(parents=True, exist_ok=True)
    Path(p).write_bytes(text.encode("utf-8"))


def slug(s, n=32):
    s = re.sub(r"`", "", s)
    s = re.sub(r"[^A-Za-z0-9]+", "-", s).strip("-").lower()
    return (s[:n].rstrip("-")) or "section"


def head_of(line):
    """(level, id|None, title) of a heading line, else None."""
    m = HEAD.match(line)
    if not m:
        return None
    level, rest = len(m.group(1)), m.group(2)
    n = NUM.match(rest)
    if n:
        return level, n.group(1), (n.group(2) or "").strip() or rest
    return level, None, rest


def heading_lines(lines):
    """indexes of heading lines outside code fences"""
    out, fence = [], False
    for i, l in enumerate(lines):
        s = l.lstrip()
        if s.startswith("```") or s.startswith("~~~"):
            fence = not fence
            continue
        if not fence and HEAD.match(l):
            out.append(i)
    return out


def nbytes(lines):
    return sum(len(l.encode("utf-8")) + 1 for l in lines)


def split_doc(path, limit):
    path = Path(path)
    text = rd(path)
    if MARK_A in text:
        sys.exit(f"{path.name} is already an index (has the sections marker)")
    lines = text.split("\n")
    heads = heading_lines(lines)
    if not heads:
        sys.exit("no headings to split on")
    # tree: each node = (start, end, level, hid, title); children are the next-level headings inside it
    def build(start, end, level):
        idx = [h for h in heads if start <= h < end and head_of(lines[h])[0] == level]
        nodes = []
        for k, h in enumerate(idx):
            e = idx[k + 1] if k + 1 < len(idx) else end
            nodes.append((h, e, level))
        return nodes

    parts = []  # (start, end, level)

    def walk(nodes):
        for (s, e, level) in nodes:
            kids = build(s + 1, e, level + 1) if level < 4 else []
            if kids and nbytes(lines[s:e]) > limit:
                parts.append((s, kids[0][0], level))  # the node's own lead text
                walk(kids)
            else:
                parts.append((s, e, level))

    walk(build(heads[0], len(lines), 2))
    first = parts[0][0]
    pre = "\n".join(lines[:first]) + ("\n" if first else "")
    if first:
        pre = "\n".join(lines[:first]) + "\n"
    # sanity: parts are contiguous from `first` to the end
    pos = first
    for (s, e, _l) in parts:
        assert s == pos, (s, pos)
        pos = e
    assert pos == len(lines), (pos, len(lines))
    folder = path.with_suffix("")
    if folder.exists() and any(folder.iterdir()):
        sys.exit(f"{folder} already exists and is not empty")
    width = 3 if len(parts) < 99 else 4
    used, written = set(), []
    for n, (s, e, _l) in enumerate(parts, 1):
        lvl, hid, title = head_of(lines[s])
        hid = hid or f"u{n}"
        name = f"{n * 10:0{width}d}_{hid}_{slug(title)}.md"
        assert name not in used
        used.add(name)
        chunk = "\n".join(lines[s:e]) + ("\n" if e < len(lines) else "")
        wr(folder / name, chunk)
        written.append(name)
    wr(path, pre + MARK_A + "\n" + MARK_B + "\n")
    rebuild_index(path)
    # lossless proof
    if join_doc(path) != text:
        sys.exit("JOIN MISMATCH after split: not lossless, original left in the index? restore from git")
    print(f"{path.name}: {len(parts)} sections in {folder.name}/ (largest {max(nbytes(lines[s:e]) for s, e, _ in parts)} B), lossless join verified")


def part_files(path):
    folder = Path(path).with_suffix("")
    return sorted(p for p in folder.glob("*.md")) if folder.is_dir() else []


def part_info(p):
    first = rd(p).split("\n", 1)[0]
    h = head_of(first)
    m = re.match(r"^(\d+)_(.+?)_", p.name)
    hid = h[1] if h and h[1] else (m.group(2) if m else "?")
    title = h[2] if h else first
    level = h[0] if h else 2
    return level, hid, title


def rebuild_index(path):
    path = Path(path)
    text = rd(path)
    a = text.find(MARK_A)
    if a < 0:
        sys.exit(f"{path.name} has no sections marker; run split first")
    pre = text[:a]
    folder = path.with_suffix("")
    rows = ["| § | Section | File | KB |", "|---|---|---|---|"]
    for p in part_files(path):
        level, hid, title = part_info(p)
        pad = "· " * (level - 2)
        kb = f"{len(p.read_bytes()) / 1024:.1f}"
        rows.append(f"| {hid} | {pad}{title.replace('|', '/')[:72]} | `{p.name}` | {kb} |")
    note = (f"## Sections\n\nStored as section files in `{folder.name}/` (next to this file); **read only the sections the step names**. "
            f"A citation `§id` resolves through this table (or Glob `{folder.name}/*_<id>_*.md`); a parent id (`§4b`) stands for itself plus its "
            f"children (rows with a longer id). `python scripts/docs_tool.py join {path.name}` prints the whole text.\n\n")
    wr(path, pre + MARK_A + "\n" + note + "\n".join(rows) + "\n" + MARK_B + "\n")


def join_doc(path):
    path = Path(path)
    text = rd(path)
    a = text.find(MARK_A)
    if a < 0:
        return text
    pre = text[:a]
    return pre + "".join(rd(p) for p in part_files(path))


# ---------------------------------------------------------------- check / budget
def indexed_docs(root):
    out = []
    for p in sorted(Path(root).rglob("*.md")):
        if "runs" in p.parts or "_backups" in p.parts:
            continue
        try:
            if MARK_A in rd(p):
                out.append(p)
        except Exception:
            pass
    return out


def skill_dirs(skills):
    return sorted(d for d in Path(skills).glob("atp-*") if d.is_dir())


CITE = re.compile(r"`([a-z0-9-]+)\.md`\s*§\s*(\d+[a-z]?(?:\.\d+[a-z]?)*)")
SKILLREF = re.compile(r"`(atp-[a-z0-9-]+)`")
PATHREF = re.compile(r"`(ATP/[^`\s]+)`")


def cmd_check(a):
    root, skills = Path(a.root), Path(a.skills)
    errs, warns = [], []
    docs = indexed_docs(root)
    ids = {}
    for d in docs:
        folder = d.with_suffix("")
        listed = re.findall(r"\| `(\d+_[^`]+\.md)` \|", rd(d))
        files = [p.name for p in part_files(d)]
        for f in listed:
            if f not in files:
                errs.append(f"{d.name}: table lists missing file {f}")
        for f in files:
            if f not in listed:
                errs.append(f"{d.name}: file {f} is not in the table (run index)")
        ids[d.stem] = {part_info(p)[1] for p in part_files(d)}
    names = {d.name for d in skill_dirs(skills)}
    scan = [(s / "SKILL.md") for s in skill_dirs(skills)] + [HOME / "commands" / "analyze-then-pick.md"]
    for s in sorted(Path(root).glob("reference/**/*.md")) + sorted(Path(root).glob("models/**/*.md")) + sorted(Path(root).glob("higgsfield/*.md")):
        if "first-party" not in s.parts:
            scan.append(s)
    for f in scan:
        if not f.is_file():
            errs.append(f"missing file {f}")
            continue
        t = rd(f)
        if f.name == "SKILL.md":
            fm = re.match(r"^---\r?\n(.*?)\r?\n---", t, re.S)
            if not fm:
                errs.append(f"{f.parent.name}: no frontmatter")
            else:
                nm = re.search(r"^name:\s*(.+?)\s*$", fm.group(1), re.M)
                ds = re.search(r"^description:\s*(.+?)\s*$", fm.group(1), re.M)
                if not nm or nm.group(1) != f.parent.name:
                    errs.append(f"{f.parent.name}: frontmatter name != folder")
                if not ds:
                    errs.append(f"{f.parent.name}: no description")
                elif len(ds.group(1)) > 200:
                    warns.append(f"{f.parent.name}: description is {len(ds.group(1))} chars (listed in every session; keep it short)")
        for m in SKILLREF.finditer(t):
            if m.group(1) not in names:
                errs.append(f"{f.relative_to(HOME)}: names skill {m.group(1)} which does not exist")
        for m in PATHREF.finditer(t):
            ref = m.group(1).rstrip(".,;:)")
            ref = ref.replace("ATP/", "", 1)
            if any(c in ref for c in "*<>{}"):
                continue
            if not (root / ref).exists():
                errs.append(f"{f.relative_to(HOME)}: path ATP/{ref} does not exist")
        for m in CITE.finditer(t):
            doc, sec = m.group(1), m.group(2)
            if doc in ids and sec not in ids[doc]:
                # an id that is not a row lives inside its nearest ancestor row, but only if that row was not split into children
                anc = sec
                while anc not in ids[doc] and "." in anc:
                    anc = anc.rsplit(".", 1)[0]
                if anc not in ids[doc] or any(i.startswith(anc + ".") for i in ids[doc]):
                    warns.append(f"{f.relative_to(HOME)}: cites {doc}.md §{sec} which is not a section id")
    for w in warns:
        print("warn:", w)
    for e in errs:
        print("ERROR:", e)
    print(f"checked {len(docs)} indexed docs, {len(names)} skills, {len(scan)} files: {len(errs)} errors, {len(warns)} warnings")
    return 1 if errs else 0


def cmd_budget(a):
    root, skills = Path(a.root), Path(a.skills)
    rows = []
    for d in skill_dirs(skills):
        t = rd(d / "SKILL.md")
        own = len(t.encode("utf-8"))
        seen, read = set(), 0
        for m in PATHREF.finditer(t):
            ref = m.group(1).rstrip(".,;:)").replace("ATP/", "", 1)
            if any(c in ref for c in "*<>{}"):
                continue
            p = root / ref
            # only documents a phase reads: sections and guides, never the files a skill names to say "never read it"
            if p.suffix == ".md" and p.is_file() and p not in seen and p.relative_to(root).parts[0] in ("reference", "models", "higgsfield", "pipeline"):
                seen.add(p)
                read += p.stat().st_size
        rows.append((d.name, own, read, len(seen)))
    print(f"{'skill':26s} {'SKILL KB':>9s} {'named files KB':>15s} {'files':>6s}")
    for n, o, r, c in rows:
        print(f"{n:26s} {o / 1024:9.1f} {r / 1024:15.1f} {c:6d}")
    cmdp = HOME / "commands" / "analyze-then-pick.md"
    print(f"\ncommand (always loaded): {cmdp.stat().st_size / 1024:.1f} KB")
    return 0


SEC_ID = re.compile(r"§\s*(\d+[a-z]?(?:\.\d+[a-z]?)*)")
DOCMENT = re.compile(r"`([a-z0-9-]+)\.md`")


def split_skill(text):
    """(the 'Read now' section, everything after it)"""
    if "## Read now" not in text:
        return "", text
    after = text.split("## Read now", 1)[1]
    read, sep, rest = after.partition("\n## ")
    return read, rest


def skill_citations(text):
    """(doc, id) pairs cited as `doc.md` §a, §b ... in a skill body after its Read-now list (the ids that follow one doc mention, up to the next doc mention)"""
    body = split_skill(text)[1]
    out = []
    mentions = list(DOCMENT.finditer(body))
    for k, m in enumerate(mentions):
        end = mentions[k + 1].start() if k + 1 < len(mentions) else len(body)
        seg = body[m.end():min(end, m.end() + 140)]
        # stop at a sentence break so a later unrelated § is not attributed to this document
        seg = re.split(r"[.;:](?:\s|$)", seg, maxsplit=1)[0] if not seg.lstrip().startswith("§") else seg
        for s in SEC_ID.finditer(seg):
            out.append((m.group(1), s.group(1)))
    return out


def row_of(rows, sec):
    anc = sec
    while anc not in rows and "." in anc:
        anc = anc.rsplit(".", 1)[0]
    return anc if anc in rows else None


def cmd_coverage(a):
    root, skills = Path(a.root), Path(a.skills)
    rows = {d.stem: {part_info(p)[1] for p in part_files(d)} for d in indexed_docs(root)}
    total = 0
    for d in skill_dirs(skills):
        if a.skill and d.name != a.skill:
            continue
        t = rd(d / "SKILL.md")
        read = split_skill(t)[0]
        have = set(re.findall(r"- ([a-z0-9-]+) §([0-9a-z.]+):", read))
        # a parent id read with its children counts for the children too
        miss = []
        for doc, sec in dict.fromkeys(skill_citations(t)):
            if doc not in rows:
                continue
            r = row_of(rows[doc], sec)
            if r is None:
                continue
            if (doc, r) in have or any(h[0] == doc and (h[1] == r or h[1].startswith(r + ".")) for h in have):
                continue
            miss.append(f"{doc} §{sec}" + (f" (row {r})" if r != sec else ""))
        if miss:
            total += len(miss)
            print(f"{d.name}: {len(miss)} cited, not in Read now: " + "; ".join(miss))
    print(f"{total} uncovered citations")
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sp = ap.add_subparsers(dest="cmd", required=True)
    s = sp.add_parser("split"); s.add_argument("doc"); s.add_argument("--limit", type=int, default=8000)
    j = sp.add_parser("join"); j.add_argument("doc"); j.add_argument("--out")
    i = sp.add_parser("index"); i.add_argument("doc")
    for nm in ("check", "budget", "coverage"):
        c = sp.add_parser(nm); c.add_argument("--root", default=str(ATP)); c.add_argument("--skills", default=str(SKILLS))
        if nm == "coverage":
            c.add_argument("--skill")
    a = ap.parse_args()
    if a.cmd == "split":
        split_doc(a.doc, a.limit)
    elif a.cmd == "join":
        t = join_doc(a.doc)
        if a.out:
            wr(a.out, t)
        else:
            sys.stdout.buffer.write(t.encode("utf-8"))
    elif a.cmd == "index":
        rebuild_index(a.doc)
    elif a.cmd == "check":
        sys.exit(cmd_check(a))
    elif a.cmd == "budget":
        sys.exit(cmd_budget(a))
    elif a.cmd == "coverage":
        sys.exit(cmd_coverage(a))


if __name__ == "__main__":
    main()
